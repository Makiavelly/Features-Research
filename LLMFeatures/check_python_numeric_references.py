"""Auditor-written SQL references for two saved real Python responses.

These queries are written by the host, not generated by the model. No unguarded exec.
"""
import json
from pathlib import Path
import sys
import numpy as np
import pandas as pd

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'data/kaggle_hm_small_sql_compare_v1'

COMMON='''
WITH u AS (
 SELECT customer_id,count(*) AS n,
 count(*) FILTER(WHERE days_ago<=30) AS n30,
 count(*) FILTER(WHERE days_ago<=365) AS n365,
 min(days_ago) AS recency,avg(price) AS mean_price,
 avg(CASE WHEN sales_channel_id=2 THEN 1.0 ELSE 0.0 END) AS channel2
 FROM history GROUP BY customer_id),
i AS (
 SELECT article_id,count(*) AS n,
 count(*) FILTER(WHERE days_ago<=7) AS n7,
 count(*) FILTER(WHERE days_ago<=30) AS n30,
 count(*) FILTER(WHERE days_ago<=90) AS n90,
 count(*) FILTER(WHERE days_ago<=365) AS n365,
 min(days_ago) AS recency,avg(price) AS mean_price,
 avg(CASE WHEN sales_channel_id=2 THEN 1.0 ELSE 0.0 END) AS channel2
 FROM history GROUP BY article_id),
pair AS (SELECT customer_id,article_id,count(*) AS n FROM history GROUP BY customer_id,article_id),
t AS (SELECT customer_id,product_type_no,count(*) AS n FROM history GROUP BY customer_id,product_type_no),
s AS (SELECT customer_id,section_no,count(*) AS n FROM history GROUP BY customer_id,section_no),
p AS (SELECT customer_id,product_code,count(*) AS n FROM history GROUP BY customer_id,product_code),
d AS (SELECT customer_id,department_no,count(*) AS n FROM history GROUP BY customer_id,department_no),
c AS (SELECT customer_id,colour_group_code,count(*) AS n FROM history GROUP BY customer_id,colour_group_code),
prod AS (SELECT product_code,count(*) AS n FROM history WHERE days_ago<=30 GROUP BY product_code)
'''
JOINS='''
FROM reference_pairs x LEFT JOIN u USING(customer_id) LEFT JOIN i USING(article_id)
LEFT JOIN pair ON pair.customer_id=x.customer_id AND pair.article_id=x.article_id
LEFT JOIN t ON t.customer_id=x.customer_id AND t.product_type_no=x.raw_i_product_type_no
LEFT JOIN s ON s.customer_id=x.customer_id AND s.section_no=x.raw_i_section_no
LEFT JOIN p ON p.customer_id=x.customer_id AND p.product_code=x.raw_i_product_code
LEFT JOIN d ON d.customer_id=x.customer_id AND d.department_no=x.raw_i_department_no
LEFT JOIN c ON c.customer_id=x.customer_id AND c.colour_group_code=x.raw_i_colour_group_code
LEFT JOIN prod ON prod.product_code=x.raw_i_product_code ORDER BY x.rid
'''
REFERENCE3='''
SELECT coalesce(i.n7,0) AS f_item_count_7d,coalesce(i.n30,0) AS f_item_count_30d,
coalesce(i.n90,0) AS f_item_count_90d,coalesce(i.n,0) AS f_item_count_all,
coalesce(u.n30,0) AS f_user_count_30d,coalesce(u.n,0) AS f_user_count_all,
u.recency AS f_user_recency,i.recency AS f_item_recency,coalesce(pair.n,0) AS f_pair_count,
coalesce(s.n/nullif(u.n,0),0) AS f_user_section_rate,
coalesce(t.n/nullif(u.n,0),0) AS f_user_type_rate
'''
REFERENCE5='''
SELECT coalesce(i.n30,0) AS f_item_count_30d,coalesce(i.n365,0) AS f_item_count_365d,
u.recency AS f_customer_recency,coalesce(u.n30,0) AS f_customer_count_30d,
coalesce(u.n365,0) AS f_customer_count_365d,
ln(1+coalesce(p.n,0)) AS f_user_product_affinity,
ln(1+coalesce(t.n,0)) AS f_user_type_affinity,
ln(1+coalesce(d.n,0)) AS f_user_department_affinity,
ln(1+coalesce(s.n,0)) AS f_user_section_affinity,
ln(1+coalesce(u.n,0)) AS f_user_item_count,i.recency AS f_item_recency,
i.channel2 AS f_item_channel2_share,i.mean_price AS f_item_mean_price,
u.mean_price AS f_user_mean_price,u.channel2 AS f_user_channel2_share,
i.mean_price-u.mean_price AS f_price_vs_user,coalesce(prod.n,0) AS f_product_count_30d
'''
REFERENCE10='''
SELECT coalesce(i.n30,0) AS f_item_count_30d,coalesce(i.n90,0) AS f_item_count_90d,
coalesce(i.n,0) AS f_item_count_all,coalesce(i.recency,-1) AS f_item_recency,
i.mean_price AS f_item_price_mean,coalesce(u.n30,0) AS f_user_count_30d,
coalesce(u.n,0) AS f_user_count_all,coalesce(u.recency,-1) AS f_user_recency,
coalesce(pair.n,0) AS f_pair_count_all,coalesce(s.n,0) AS f_user_section_count,
coalesce(p.n,0) AS f_user_product_count,coalesce(c.n,0) AS f_user_colour_count
'''


def main():
    current=json.loads((ROOT/'reports/provider_python_v1/current_run.json').read_text())
    source=Path(current['directory'])
    sys.path.insert(0,str(source/'runtime_sources'))
    from python_features import FeatureEngine
    out=ROOT/'reports/gpt61sol_python_v1'
    out.mkdir(exist_ok=True)
    engine=FeatureEngine(out/'numeric_reference_scratch',DATA)
    pairs=pd.read_parquet(DATA/'train_pairs.parquet')
    checked=[]
    try:
        for call,sql in [(3,REFERENCE3),(5,REFERENCE5),(10,REFERENCE10)]:
            folder=source/'gpt61sol_python/candidates'/f'candidate_{call:03d}'
            program=json.loads((folder/'program.json').read_text())
            features=None
            checked_rows=0
            for cutoff,group in pairs.groupby('timestamp',sort=True):
                sample=group if call==10 else group.head(128)
                engine.prepare(cutoff,sample.customer_id.values,program)
                frame=engine.frame(sample)
                features=engine.names
                X=pd.concat([sample[['customer_id','article_id']].reset_index(drop=True),frame[engine.raw_names]],axis=1)
                X.insert(0,'rid',np.arange(len(X)))
                engine.con.register('reference_pairs',X)
                expected=engine.con.sql(COMMON+sql+JOINS).df()
                engine.con.unregister('reference_pairs')
                assert set(features)==set(expected), (call,features,list(expected))
                np.testing.assert_allclose(frame[features].to_numpy(dtype=float),expected[features].to_numpy(dtype=float),rtol=1e-10,atol=1e-10,equal_nan=True)
                if call==10:
                    np.testing.assert_array_equal(frame[features].to_numpy(dtype=np.float32),expected[features].to_numpy(dtype=np.float32))
                checked_rows+=len(sample)
            checked.append({'call':call,'cutoffs':8,'features':len(features),'exact_feature_names':features,
                            'rows':checked_rows,'float32_exact':call==10,
                            'status':'passed','reference_sql':COMMON+sql+JOINS})
            print('Independent SQL reference passed:',call,len(features),'features x8cutoffs',flush=True)
    finally:engine.close()
    result={'status':'passed','checks':checked,'api_calls':0,'training_runs':0,
            'scope':'Three real responses manually translated to independent SQL. Selected call10 checked on all72813 train rows with exact float32 equality; calls3/5 on128 rows per cutoff. Not a claim to verify every proposed formula.'}
    (out/'numeric_reference_verification.json').write_text(json.dumps(result,indent=2))


if __name__=='__main__':main()
