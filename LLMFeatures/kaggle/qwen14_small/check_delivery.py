"""Verify matched protocol and single-model report with frozen CPU test fixtures."""
import ast
import hashlib
import json
from pathlib import Path
import shutil
import sys
import numpy as np
import pandas as pd
import nbformat

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import runtime14


def assignment(notebook, name):
    for cell in notebook['cells']:
        if cell['cell_type'] != 'code':
            continue
        for node in ast.parse(''.join(cell['source'])).body:
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == name:
                return node.value
    raise ValueError(name)


def main():
    parent = json.loads((HERE.parent / 'hm_small_qwen_vs_llama_sql_kaggle_t4.ipynb').read_text(encoding='utf-8'))
    notebook = json.loads((HERE.parent / 'hm_small_qwen14b_sql_kaggle_t4.ipynb').read_text(encoding='utf-8'))
    nbformat.validate(nbformat.from_dict(notebook))
    for cell in notebook['cells']:
        if cell['cell_type'] == 'code':
            ast.parse(''.join(cell['source']))
    old_modules = ast.literal_eval(assignment(parent, 'MODULES'))
    new_modules = ast.literal_eval(assignment(notebook, 'MODULES'))
    for name, code in old_modules.items():
        assert code == new_modules[name], 'Shared module changed: ' + name
    for name, code in new_modules.items():
        assert code == (HERE / name).read_text(encoding='utf-8')
    class Constants(ast.NodeTransformer):
        def visit_Name(self, node):
            return ast.copy_location(ast.Constant('hf'), node) if node.id == 'LLAMA_SOURCE' else node
    old_config = ast.literal_eval(Constants().visit(assignment(parent, 'CONFIG')))
    new_config = ast.literal_eval(assignment(notebook, 'CONFIG'))
    differences = {key for key in set(old_config) | set(new_config) if old_config.get(key) != new_config.get(key)}
    assert differences == {'protocol', 'llama_source'}
    assert ast.literal_eval(assignment(notebook, 'MODELS')) == {
        'qwen14b': {'model_id': 'Qwen/Qwen2.5-Coder-14B-Instruct', 'revision': None}}
    code_cells = '\n'.join(''.join(c['source']) for c in notebook['cells'] if c['cell_type'] == 'code')
    assert 'get_secret' not in code_cells and 'PREVIOUS_RESULTS' not in code_cells
    assert "for label in ['qwen14b']" in code_cells and "import runtime14 as experiment" in code_cells
    manifest = json.loads((HERE / 'delivery_manifest.json').read_text())
    assert runtime14.sha(HERE.parent / 'hm_small_qwen_vs_llama_sql_kaggle_t4.ipynb') == manifest['parent_notebook_sha256']
    assert runtime14.sha(HERE.parent / manifest['dataset']) == manifest['dataset_sha256']
    data = ROOT / 'data/kaggle_hm_small_sql_compare_v1'
    assert runtime14.sha(data / 'manifest.json') == manifest['bundle_manifest_sha256']
    prior = ROOT / 'reports/kaggle_llmfe_validation/small_compare_v1/cpu_smoke_dense_v2'
    assert json.loads((prior.parent / 'verification.json').read_text())['status'] == 'passed'
    out = ROOT / 'reports/kaggle_llmfe_validation/qwen14_small_v1/cpu_smoke'
    out.mkdir(parents=True, exist_ok=True)
    # Test fixtures are manually specified SQL programs, NOT generated by any LLM.
    # The unchanged evaluator was previously trained/replayed on the identical72813pairs.
    shutil.copytree(prior / 'raw_control', out / 'raw_control', dirs_exist_ok=True)
    selected = json.loads((prior / 'qwen/selected.json').read_text())
    source = Path(selected['directory'])
    destination = out / 'qwen14b/candidates' / source.name
    shutil.copytree(source, destination, dirs_exist_ok=True)
    selected['directory'] = str(destination)
    runtime14.write(out / 'qwen14b/selected.json', selected)
    config = json.loads((prior / 'run_config.json').read_text())
    config['validation_only_fake_callbacks'] = True
    config['protocol'] = new_config['protocol']
    runtime14.write(out / 'run_config.json', config)
    # The exact same initial prompt follows from the matched settings/examples.
    best = {'score': .01, 'program': {'aggregates': [], 'derived': []}}
    same_examples = {**new_config, 'train_pairs': 72813, 'training_examples': '[]'}
    old_examples = {**old_config, 'train_pairs': 72813, 'training_examples': '[]'}
    assert runtime14.make_prompt(data, best, None, same_examples) == runtime14.make_prompt(data, best, None, old_examples)
    frame = runtime14.finish(data, out, out / 'run_config.json')
    assert len(frame) == 10
    assert 'qwen14b_LightGBM' in frame.model.values
    assert 'qwen_LightGBM' not in frame.model.values and 'llama_LightGBM' not in frame.model.values
    expected = pd.read_csv(prior / 'comparison.csv').set_index('model').loc['qwen_LightGBM', 'test_map_percent']
    actual = frame.set_index('model').loc['qwen14b_LightGBM', 'test_map_percent']
    assert np.isclose(actual, expected, atol=1e-12)
    assert 'qwen14b_minus_raw_pp' in json.loads((out / 'paired_bootstrap.json').read_text())
    for name in ['comparison.png', 'test_histograms.png', 'lightgbm_training.png', 'report.md', 'complete.json']:
        assert (out / name).exists()
    report = {'status': 'passed', 'scope': 'Single-model reporting adapter with frozen CPU fixtures; no real14B inference',
              'shared_four_modules_byte_identical': True, 'protocol_differences': sorted(differences),
              'initial_prompt_identical': True, 'same_bundle_and_train_pairs': True,
              'only_qwen14b_scheduled': True, 'requires_previous_llm_outputs': False,
              'no_hf_secret_required': True, 'frozen_fixture_metrics_unchanged': True,
              'references_recomputed_from_predictions': 7, 'plots_and_zip_created': True,
              'notebook_sha256': runtime14.sha(HERE.parent / 'hm_small_qwen14b_sql_kaggle_t4.ipynb')}
    runtime14.write(out.parent / 'verification.json', report)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
